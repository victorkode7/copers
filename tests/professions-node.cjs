const assert = require('node:assert/strict');
const fs = require('node:fs'), vm = require('node:vm');
const sandbox = {};vm.runInNewContext(fs.readFileSync('js/professions.js','utf8'),sandbox);
const P = sandbox.Professions, json = value => JSON.parse(JSON.stringify(value));
const p = {professions:P.defaults(),level:10,experience:50,skillPoints:3};
assert.equal(P.progress(p.professions,'alchemy').level,1);
assert.equal(P.progress(p.professions,'alchemy').required,100);
assert.equal(P.awardXp(p,'alchemy',99).levelsGained,0);
assert.equal(P.awardXp(p,'alchemy',1).levelsGained,1);
assert.equal(P.progress(p.professions,'alchemy').earned,0);
assert.equal(P.awardXp(p,'alchemy',500).levelsGained,2);
assert.equal(P.progress(p.professions,'alchemy').level,4);
assert.deepEqual(Object.keys(P.definitions),['alchemy']);
assert.deepEqual(Object.keys(P.defaults().xp),['alchemy']);
assert.deepEqual([p.level,p.experience,p.skillPoints],[10,50,3]);
const before = json(p);
for (const amount of [0,-1,.5,NaN,Infinity,'2',Number.MAX_SAFE_INTEGER+1]) assert.equal(P.awardXp(p,'alchemy',amount),null);
for (const id of ['woodcutting','mining','smithing','crafting','missing','constructor','__proto__',null]) assert.equal(P.awardXp(p,id,10),null);
assert.deepEqual(json(p),before);
assert.equal(P.awardXp(p,'alchemy',Number.MAX_SAFE_INTEGER).level,99);
assert.equal(P.awardXp(p,'alchemy',1).added,0);
assert.equal(P.progress(p.professions,'alchemy').fraction,1);
const bulk = {professions:P.defaults()}, steps = {professions:P.defaults()};
P.awardXp(bulk,'alchemy',12345);for(let i=0;i<12345;i++) P.awardXp(steps,'alchemy',1);
assert.deepEqual(json(bulk),json(steps));
assert.deepEqual(json(P.normalize(json(p.professions))),json(p.professions));
assert.deepEqual(json(P.normalize()),json(P.defaults()));
const old = {version:1,xp:{fishing:400},future:{value:1}};
const normalized = P.normalize(old);assert.equal(normalized.xp.alchemy,0);assert.equal(normalized.xp.fishing,400);
assert.deepEqual(json(old),{version:1,xp:{fishing:400},future:{value:1}});
for(const value of [null,[],{version:2,xp:{}},{version:1,xp:[]},...[-1,.5,'10',null,P.maxXp+1].map(alchemy=>({version:1,xp:{alchemy}}))]) assert.throws(()=>P.normalize(value));
assert.throws(()=>P.normalize(JSON.parse('{"version":1,"xp":{"__proto__":0}}')));
console.log('PROFESSIONS TESTS PASSED');
