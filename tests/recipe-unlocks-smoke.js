        materialSources.ore = [source(secondMaps[1])]; renderCrafting();
        check('later maps within an unlocked world still gate their materials', !visible());
        state.kills[secondMaps[0].id] = secondMaps[0].goal; renderCrafting();
        check('unlocking the required later map reveals the recipe', visible());
        recipe.materials = {crystal: 1}; state.materials.crystal = 100; renderCrafting();
