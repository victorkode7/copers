        state.kills[firstMaps[woodsIndex - 1].id] = 0; renderCrafting();
        check('show hidden never bypasses area requirements for crafted recipes', !visible());
        state.ownedItemIds = []; state.crafted = []; recipe.materials = {gel: 2, ore: 1};
        state.kills = Object.fromEntries(mapData.map(map => [map.id, 0])); renderCrafting();
